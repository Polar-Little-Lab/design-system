import fs from 'node:fs';
const tokens=JSON.parse(fs.readFileSync(new URL('../tokens/frost.json',import.meta.url),'utf8'));
const lines=['/* Generated by npm run tokens. Edit tokens/frost.json. */',':root {'];
for(const [group,values] of Object.entries(tokens)) for(const [key,value] of Object.entries(values)){
 const name=key.replace(/[A-Z]/g,x=>'-'+x.toLowerCase());
 lines.push('  --polar-'+group+'-'+name+': '+value+(typeof value==='number'?'px':'')+';');
}
lines.push('}');
fs.writeFileSync(new URL('../src/tokens.css',import.meta.url),lines.join('\n')+'\n');
fs.writeFileSync(new URL('../adapters/qt/src/polar_ui/tokens.json',import.meta.url),JSON.stringify(tokens,null,2)+'\n');
